SET DEFINE OFF;
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
    'OTP_POOL', 'CASE_HEARING', 'COURT', 'SUSPECT', 'EVIDENCE', 'DIGITAL_DEVICE',
    'CYBER_CRIME_CASE', 'CYBER_CRIME_TYPE', 'INVESTIGATOR', 'POLICE_DEPARTMENT',
    'VICTIM', 'LOGIN'
  )) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE "' || t.table_name || '" CASCADE CONSTRAINTS';
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
  END LOOP;
END;
/
EXIT;
