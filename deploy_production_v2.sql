BEGIN
  FOR cur_rec IN (SELECT table_name FROM user_tables WHERE table_name IN (
    'CASE_HEARING', 'COURT', 'SUSPECT', 'EVIDENCE', 'DIGITAL_DEVICE',
    'CYBER_CRIME_CASE', 'CYBER_CRIME_TYPE', 'INVESTIGATOR', 'POLICE_DEPARTMENT',
    'VICTIM', 'OTP_AUDIT_LOG', 'OTP_POOL', 'LOGIN'
  )) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE "' || cur_rec.table_name || '" CASCADE CONSTRAINTS';
    EXCEPTION
      WHEN OTHERS THEN NULL;
    END;
  END LOOP;
END;
/

BEGIN
  FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name IN (
    'SEQ_USER_ID', 'SEQ_VICTIM_ID', 'SEQ_CASE_ID', 'SEQ_DEVICE_ID', 'SEQ_EVIDENCE_ID', 'SEQ_SUSPECT_ID', 'SEQ_POOL_ID'
  )) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP SEQUENCE "' || s.sequence_name || '"';
    EXCEPTION
      WHEN OTHERS THEN NULL;
    END;
  END LOOP;
END;
